Write-Host "============================================================"
Write-Host "[ALL TESTS PASSED]"
Write-Host "ASM:       $AsmFile"
Write-Host "Text HEX:  $TextFile"
Write-Host "Data HEX:  $DataFile"
Write-Host "Image:     $ImageFile"
Write-Host "Resealed:  $ResealedImageFile"
Write-Host "============================================================"

